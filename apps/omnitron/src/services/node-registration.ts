/** Private on-node snapshots survive controller failure; application data is never copied or replaced. */
export function prepareNodeConfigPublication(input: {
  directory: string; project: string; body: string; operation: string;
  artifacts: ReadonlyArray<{ app: string; version: string; directory?: string }>;
}): { command: string; stdin: string } {
  const command = remoteNode(`import fs from 'node:fs'; import path from 'node:path'; import {pathToFileURL} from 'node:url'; import {createHash} from 'node:crypto';
    class RegistrationError extends Error {}
    try {
    let size=0; const chunks=[];
    for await(const chunk of process.stdin){size+=chunk.length;if(size>16*1024*1024)throw new RegistrationError('Node configuration input exceeds 16 MiB');chunks.push(chunk)}
    let input;try{input=JSON.parse(Buffer.concat(chunks).toString('utf8'))}catch{throw new RegistrationError('Invalid node configuration input')}
    if(!input||typeof input.body!=='string'||typeof input.directory!=='string'||typeof input.project!=='string'||typeof input.operation!=='string'||!Array.isArray(input.artifacts))throw new RegistrationError('Invalid node configuration input');
    const directory=input.directory;
    fs.mkdirSync(directory,{recursive:true,mode:0o700});
    const snapshot=path.join(directory,'.registration-'+input.operation);
    fs.mkdirSync(snapshot,{mode:0o700});
    const files=['omnitron.config.mjs','omnitron.host-upgrade.json','.omnitron-config-sha256'];
    const present=files.filter(name=>fs.existsSync(path.join(directory,name)));
    for(const name of present) fs.copyFileSync(path.join(directory,name),path.join(snapshot,name));
    fs.writeFileSync(path.join(snapshot,'present.json'),JSON.stringify(present),{mode:0o600});
    const write=(file,body)=>{const temporary=file+'.part-'+input.operation; const fd=fs.openSync(temporary,'wx',0o600);
      try{fs.writeFileSync(fd,body);fs.fsyncSync(fd)}finally{fs.closeSync(fd)}fs.renameSync(temporary,file)};
    const staged=path.join(snapshot,'candidate.mjs'); write(staged,input.body);
    const candidate=(await import(pathToFileURL(staged).href)).default;
    const configFile=path.join(directory,files[0]);
    const previous=fs.existsSync(configFile)?(await import(pathToFileURL(configFile).href)).default:null;
    const priorOrigin=previous?.stacks?.deployed?.managedOrigin;
    const nextOrigin=candidate.stacks?.deployed?.managedOrigin;
    if(priorOrigin&&(!nextOrigin||priorOrigin.project!==nextOrigin.project||priorOrigin.stack!==nextOrigin.stack))
      throw new RegistrationError('Node allocation belongs to another source stack; configuration retained');
    if(nextOrigin&&!priorOrigin&&(previous?.apps?.length??0)>0)
      throw new RegistrationError('Legacy node allocation must be explicitly bound to its source stack before deployment; configuration retained');
    const merged=new Map((previous?.apps??[]).map(app=>[app.name,app]));
    for(const app of candidate.apps) merged.set(app.name,app);
    candidate.apps=[...merged.values()];
    candidate.stacks={...previous?.stacks,...candidate.stacks,deployed:{...candidate.stacks?.deployed,type:'local',apps:candidate.apps.map(app=>app.name)}};
    const body='// Generated by Omnitron. Contains credentials; keep private.\\nexport default '+JSON.stringify(candidate,null,2)+';\\n';
    const hash=createHash('sha256').update(body).digest('hex');
    write(path.join(snapshot,'activation.json'),JSON.stringify({hash,apps:candidate.stacks.deployed.apps}));
    const changed=!fs.existsSync(configFile)||fs.readFileSync(configFile,'utf8')!==body;
    const contractFile=path.join(directory,files[1]);
    if(fs.existsSync(contractFile)){
      const contract=JSON.parse(fs.readFileSync(contractFile,'utf8'));
      if(contract.schema!==1||!Array.isArray(contract.apps)) throw new RegistrationError('Unsupported host upgrade contract; configuration retained');
      for(const artifact of input.artifacts){
        const name=input.project+'/deployed/'+artifact.app;
        const binding=contract.apps.find(app=>app.name===name);
        if(!binding) throw new RegistrationError('Explicit host upgrade contract required for new app: '+name);
        binding.cwd=candidate.apps.find(app=>app.name===artifact.app).cwd;
        binding.version=artifact.version;
        if(fs.realpathSync(binding.cwd)!==binding.cwd) throw new RegistrationError('Release directory must be canonical: '+name);
      }
      write(contractFile,JSON.stringify(contract,null,2)+'\\n');
    }
    write(configFile,body); write(path.join(directory,files[2]),hash);
    const fd=fs.openSync(directory,'r');try{fs.fsyncSync(fd)}finally{fs.closeSync(fd)}
    console.log(JSON.stringify({changed}));
    }catch(error){
      const safeCodes=new Set(['EACCES','ENOENT','ENOSPC','EEXIST','EROFS','EMFILE','ENFILE','ELOOP','EIO']);
      console.error(error instanceof RegistrationError?error.message:'Node configuration publication failed'+(safeCodes.has(error?.code)?' ('+error.code+')':''));
      process.exitCode=1;
    }`);
  return { command, stdin: JSON.stringify(input) };
}

export function restoreNodeConfigCommand(directory: string, operation: string): string {
  return remoteNode(`import fs from 'node:fs';import path from 'node:path';
    const directory=${JSON.stringify(directory)},snapshot=path.join(directory,${JSON.stringify('.registration-' + operation)});
    const present=JSON.parse(fs.readFileSync(path.join(snapshot,'present.json'),'utf8'));
    for(const name of ['omnitron.config.mjs','omnitron.host-upgrade.json','.omnitron-config-sha256']){
      const file=path.join(directory,name);
      if(present.includes(name)){const temporary=file+'.restore';fs.copyFileSync(path.join(snapshot,name),temporary);fs.chmodSync(temporary,0o600);fs.renameSync(temporary,file)}
      else fs.rmSync(file,{force:true});
    }
    const fd=fs.openSync(directory,'r');try{fs.fsyncSync(fd)}finally{fs.closeSync(fd)};`);
}

/** A lost SSH reply can be recovered from the command that actually ran on the node. */
export function nodeStackActivationCommand(directory: string, operation: string, project: string, stack: string, readOnly = false): string {
  return remoteNode(`import fs from 'node:fs'; import path from 'node:path';
    import { createHash } from 'node:crypto'; import { spawnSync } from 'node:child_process';
    const directory=${JSON.stringify(directory)}, operation=${JSON.stringify(operation)};
    const project=${JSON.stringify(project)}, stack=${JSON.stringify(stack)};
    const snapshot=path.join(directory,'.registration-'+operation);
    const resultFile=path.join(snapshot,'start-result.json');
    const requested=path.join(snapshot,'start-requested');
    const expected=JSON.parse(fs.readFileSync(path.join(snapshot,'activation.json'),'utf8'));
    const sameConfig=()=>fs.existsSync(path.join(directory,'omnitron.config.mjs')) &&
      expected.hash===createHash('sha256').update(fs.readFileSync(path.join(directory,'omnitron.config.mjs'))).digest('hex');
    const syncDirectory=()=>{const fd=fs.openSync(snapshot,'r');try{fs.fsyncSync(fd)}finally{fs.closeSync(fd)}};
    const writeNew=(file,value)=>{const fd=fs.openSync(file,'wx',0o600);try{fs.writeFileSync(fd,value);fs.fsyncSync(fd)}finally{fs.closeSync(fd)}};
    const unconfirmed=(reason)=>({operation,project,stack,confirmed:false,apps:[],reason});
    const parse=(output)=>{try{return JSON.parse(output)}catch{return null}};
    function startResult(child) {
      if (child.error || child.signal) {
        return unconfirmed(['ENOENT','EACCES'].includes(child.error?.code) ? 'cli-unavailable' : 'cli-interrupted');
      }
      const reply = parse(child.stdout);
      const report = reply ?? parse(child.stderr);
      if (report?.ok === false) {
        const scoped = report.project === project && report.stack === stack;
        const reasons = report.outcome === 'refused' ? ${JSON.stringify(Object.keys(stackStartRefusals))} :
          report.outcome === 'unknown' ? ['client-timeout','connection-lost'] : [];
        return unconfirmed(scoped && reasons.includes(report.reason) ? report.reason : 'cli-error');
      }
      const data = reply?.data;
      if (reply?.ok !== true || data?.action !== 'started' || data.project !== project || data.stack !== stack) {
        return unconfirmed('invalid-reply');
      }
      if (['partial','failed'].includes(data.outcome)) {
        const receipt = unconfirmed(data.outcome);
        if (Number.isSafeInteger(data.online) && Number.isSafeInteger(data.total) && data.online >= 0 && data.total >= data.online) {
          receipt.online = data.online;
          receipt.total = data.total;
        }
        return receipt;
      }
      if (child.status !== 0 || data.outcome !== 'confirmed') return unconfirmed('invalid-reply');
      const apps = Array.isArray(data.apps) ? data.apps : [];
      const names = new Set(apps.map(app => app?.name));
      const matches = apps.length > 0 && apps.length === names.size && data.total === apps.length && data.online === data.total &&
        apps.every(app => typeof app?.name === 'string' && app.status === 'online') &&
        expected.apps.length === names.size && new Set(expected.apps).size === names.size &&
        expected.apps.every(name => names.has(name) || names.has(project+'/'+stack+'/'+name));
      return matches ? {operation,project,stack,confirmed:true,apps:[...names]} : unconfirmed('application-set');
    }
    let result=unconfirmed('configuration-changed');
    if (sameConfig()) {
      if (!${readOnly} && !fs.existsSync(resultFile)) {
        let claimed=false;
        try {writeNew(requested,operation);syncDirectory();claimed=true}
        catch(error){if(error.code!=='EEXIST')throw error}
        if(claimed){
          const child=spawnSync('omnitron',['--json','stack','start',project,stack],{encoding:'utf8',maxBuffer:16*1024*1024,stdio:['ignore','pipe','pipe']});
          writeNew(resultFile+'.part',JSON.stringify(startResult(child)));fs.renameSync(resultFile+'.part',resultFile);syncDirectory();
        }
      }
      if(!sameConfig()) result=unconfirmed('configuration-changed');
      else if(fs.existsSync(resultFile)) result=JSON.parse(fs.readFileSync(resultFile,'utf8'));
      else result=unconfirmed(fs.existsSync(requested)?'result-pending':'not-requested');
    }
    process.stdout.write(JSON.stringify(result));`);
}

const startDiagnostics = {
  ...stackStartRefusals,
  'configuration-changed': 'The published node configuration changed',
  'not-requested': 'No start request was recorded on the node',
  'result-pending': 'The node recorded the start request and has no final result yet',
  'cli-unavailable': 'The node could not launch its CLI',
  'cli-interrupted': 'The node CLI was interrupted',
  'cli-error': 'The node CLI returned an error for the start request',
  'client-timeout': 'The node CLI timed out waiting for the daemon',
  'connection-lost': 'The node CLI lost its connection to the daemon',
  'invalid-reply': 'The node CLI did not return a valid start result',
  partial: 'The node reported a partial start',
  failed: 'The node reported a failed start',
  'application-set': 'The node did not confirm the complete registered application set',
};

/** Return only diagnostics from the scoped receipt that are safe to display off-node. */
export function nodeStackActivationIssue(raw: string, operation: string, project: string, stack: string, expected: string[]): string | undefined {
  const unknown = 'A matching startup confirmation is unavailable';
  try {
    const receipt = JSON.parse(raw);
    if (receipt?.operation !== operation || receipt.project !== project || receipt.stack !== stack || !expected.length) return unknown;
    if (receipt.confirmed === true && Array.isArray(receipt.apps)) {
      const online = new Set(receipt.apps);
      return expected.length === online.size && online.size === receipt.apps.length && new Set(expected).size === expected.length &&
        expected.every(name => online.has(name) || online.has(`${project}/${stack}/${name}`)) ? undefined : startDiagnostics['application-set'];
    }
    if (receipt.confirmed !== false || typeof receipt.reason !== 'string' || !Object.hasOwn(startDiagnostics, receipt.reason)) return unknown;
    const detail = startDiagnostics[receipt.reason as keyof typeof startDiagnostics];
    if ((receipt.reason === 'partial' || receipt.reason === 'failed') && Number.isSafeInteger(receipt.online) &&
        Number.isSafeInteger(receipt.total) && receipt.online >= 0 && receipt.total >= receipt.online) {
      return `${detail} (${receipt.online}/${receipt.total} applications online)`;
    }
    return detail;
  } catch { return unknown; }
}

