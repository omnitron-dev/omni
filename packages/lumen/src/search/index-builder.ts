import type { CorpusGraph } from '../corpus/graph.js';
import { extractAstPlainText, projectCorpus, type CorpusProjectionOptions } from '../corpus/projection.js';
import type { LumenConfig } from '../config/schema.js';
import { tokenizeMultilingual } from './tokenizer.js';

export interface SearchIndexEntry {
  id?: string;
  path: string;
  url?: string;
  title: string;
  excerpt?: string;
  tokens: string[];
}

export interface SearchIndexResult {
  manifestEntries: Record<string, string>;
  entries: SearchIndexEntry[];
  files: Record<string, string>;
}

function buildExcerptText(projectedBodyText?: string, fallbackTitle?: string): string {
  if (!projectedBodyText) {
    return fallbackTitle ?? '';
  }
  const stripped = projectedBodyText.replace(/\s+/g, ' ').trim();
  return stripped.slice(0, 240);
}

/**
 * Generates a portable ESM Pagefind-compatible client search runtime that loads
 * `./search-index.json` (via fetch over HTTP/HTTPS or node:fs/promises over file://)
 * and implements PagefindAdapter's `init()` and `search(query)` contract.
 */
export function createPagefindRuntimeScript(): string {
  return `// Auto-generated by @omnitron-dev/lumen SSG Search Engine
let shardCache = null;

function escapeSnippetHtml(text) {
  return String(text || '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

function tokenizeQuery(query) {
  if (!query || typeof query !== 'string') return [];
  const unescaped = query.replace(/\\\\([^\\p{L}\\p{N}\\s])/gu, '$1');
  const matches = unescaped.toLowerCase().normalize('NFKC').match(/[\\p{L}\\p{N}]+/gu);
  return matches ? matches.filter((t) => t.length > 0) : [];
}

function highlightExcerpt(excerpt, terms) {
  let safe = escapeSnippetHtml(excerpt);
  if (!safe || terms.length === 0) return safe;
  for (const term of terms) {
    if (!term) continue;
    const regex = new RegExp('(' + term + ')', 'giu');
    safe = safe.replace(regex, '<mark>$1</mark>');
  }
  return safe;
}

async function loadShardIndex() {
  if (shardCache) return shardCache;
  const shardUrl = new URL('./search-index.json', import.meta.url);
  if (shardUrl.protocol === 'file:') {
    const fsMod = await import('node:fs/promises');
    const rawJson = await fsMod.readFile(shardUrl, 'utf8');
    shardCache = JSON.parse(rawJson);
    return shardCache;
  }
  if (typeof fetch === 'function') {
    const res = await fetch(shardUrl.href);
    if (res.ok) {
      shardCache = await res.json();
      return shardCache;
    }
  }
  shardCache = { entries: [] };
  return shardCache;
}

export async function init() {
  await loadShardIndex();
  return true;
}

export async function options() {
  return true;
}

export async function search(query) {
  const index = await loadShardIndex();
  const terms = tokenizeQuery(query);
  if (terms.length === 0) {
    return { results: [] };
  }

  const entries = Array.isArray(index?.entries) ? index.entries : [];
  const scored = [];

  for (const entry of entries) {
    const tokenSet = new Set(Array.isArray(entry.tokens) ? entry.tokens : []);
    const titleLower = String(entry.title || '').toLowerCase();
    const excerptLower = String(entry.excerpt || '').toLowerCase();
    let score = 0;

    for (const term of terms) {
      if (tokenSet.has(term)) {
        score += 3;
      } else {
        for (const tok of tokenSet) {
          if (tok.includes(term)) {
            score += 1;
            break;
          }
        }
      }
      if (titleLower.includes(term)) {
        score += 5;
      } else if (excerptLower.includes(term)) {
        score += 1;
      }
    }

    if (score > 0) {
      const url = entry.url || entry.path || '/';
      const title = entry.title || url;
      const highlighted = highlightExcerpt(entry.excerpt || title, terms);
      scored.push({
        id: entry.id || url,
        score,
        data: async () => ({
          url,
          meta: { title },
          excerpt: highlighted,
        }),
      });
    }
  }

  scored.sort((a, b) => b.score - a.score);
  return { results: scored };
}

export default { init, options, search };
`;
}

export async function buildSearchIndex(
  corpus: CorpusGraph,
  config?: LumenConfig,
  options?: CorpusProjectionOptions
): Promise<SearchIndexResult> {
  const projectedCorpus = projectCorpus(corpus, options);
  const docs = projectedCorpus.getAllDocuments();
  const entries: SearchIndexEntry[] = [];

  let basePrefix = (config?.baseUrl ?? '/').replace(/\/+$/, '');
  if (basePrefix === '/') basePrefix = '';

  for (const doc of docs) {
    const textParts: string[] = [];
    if (typeof doc.title === 'string' && doc.title.length > 0) {
      textParts.push(doc.title);
    }
    if (typeof doc.path === 'string' && doc.path.length > 0) {
      textParts.push(doc.path);
    }
    for (const anchor of doc.anchors ?? []) {
      if (anchor) textParts.push(anchor);
    }
    if (doc.mathObjects) {
      for (const m of doc.mathObjects) {
        if (m.id) textParts.push(m.id);
        if (m.title) textParts.push(m.title);
      }
    }

    // Derive body text strictly from projected AST child nodes (never rawContent!)
    const projectedBodyText = doc.ast?.children ? extractAstPlainText(doc.ast.children) : '';
    if (projectedBodyText) {
      textParts.push(projectedBodyText);
    }

    const rawRoute = doc.routePath ?? `/${doc.path.replace(/\.(pdx|md)$/, '')}`;
    const normalizedPath = rawRoute.startsWith('/') ? rawRoute : `/${rawRoute}`;
    const resolvedUrl =
      basePrefix && !normalizedPath.startsWith(`${basePrefix}/`) ? `${basePrefix}${normalizedPath}` : normalizedPath;
    const safeTitle = typeof doc.title === 'string' ? doc.title : '';

    const tokens = tokenizeMultilingual(textParts.join(' '));
    entries.push({
      id: doc.id,
      path: normalizedPath,
      url: resolvedUrl,
      title: safeTitle,
      excerpt: buildExcerptText(projectedBodyText, safeTitle),
      tokens: Array.from(new Set(tokens)),
    });
  }

  const shardPayload = JSON.stringify(
    {
      version: '1.0.0',
      generatedBy: '@omnitron-dev/lumen',
      documentCount: entries.length,
      entries,
    },
    null,
    2
  );

  const entryPayload = JSON.stringify(
    {
      version: '1.0.0',
      languages: {
        [config?.defaultLocale || 'en']: {
          hash: 'lumen-shard',
          wasm: null,
          page_count: entries.length,
        },
      },
    },
    null,
    2
  );

  const runtimeScript = createPagefindRuntimeScript();

  const files: Record<string, string> = {
    'pagefind/pagefind.js': runtimeScript,
    'pagefind/search-index.json': shardPayload,
    'pagefind/pagefind-entry.json': entryPayload,
  };

  const manifestEntries: Record<string, string> = {
    'pagefind/pagefind.js': 'pagefind/pagefind.js',
    'pagefind/search-index.json': 'pagefind/search-index.json',
    'pagefind/pagefind-entry.json': 'pagefind/pagefind-entry.json',
    'pagefind/pagefind.wasm': 'pagefind/pagefind.wasm',
  };

  return {
    manifestEntries,
    entries,
    files,
  };
}

export async function generateSearchIndex(
  corpus: CorpusGraph,
  config?: LumenConfig,
  options?: CorpusProjectionOptions
): Promise<SearchIndexResult> {
  return buildSearchIndex(corpus, config, options);
}
