export interface DocusaurusConfigInput {
  title?: string;
  tagline?: string;
  url?: string;
  baseUrl?: string;
  trailingSlash?: boolean;
  onBrokenLinks?: 'throw' | 'warn' | 'ignore' | 'log';
  onBrokenAnchors?: 'throw' | 'warn' | 'ignore' | 'log';
  i18n?: {
    defaultLocale?: string;
    locales?: string[];
    localeConfigs?: Record<string, unknown>;
  };
  themeConfig?: {
    colorMode?: {
      defaultMode?: 'light' | 'dark';
    };
    navbar?: Record<string, unknown>;
    footer?: Record<string, unknown>;
    [key: string]: unknown;
  };
  plugins?: unknown[];
  presets?: unknown[];
  customFields?: Record<string, unknown>;
  katexMacros?: Record<string, string>;
  [key: string]: unknown;
}

export interface SidebarDocItem {
  type: 'doc';
  id: string;
  label?: string;
}

export interface SidebarCategoryItem {
  type: 'category';
  label: string;
  collapsed?: boolean;
  collapsible?: boolean;
  link?: {
    type?: string;
    title?: string;
    slug?: string;
    id?: string;
    [key: string]: unknown;
  };
  href?: string;
  items: SidebarItem[];
}

export interface SidebarLinkItem {
  type: 'link';
  label: string;
  href: string;
}

export interface SidebarAutogeneratedItem {
  type: 'autogenerated';
  dirName: string;
}

export type SidebarItem =
  string | SidebarDocItem | SidebarCategoryItem | SidebarLinkItem | SidebarAutogeneratedItem | Record<string, unknown>;

export interface ConvertedLumenConfig {
  title: string;
  tagline?: string;
  url?: string;
  baseUrl: string;
  trailingSlash?: boolean;
  onBrokenLinks?: 'throw' | 'warn' | 'ignore' | 'log';
  onBrokenAnchors?: 'throw' | 'warn' | 'ignore' | 'log';
  locales: string[];
  defaultLocale: string;
  sidebars: Record<string, unknown[]>;
  katexMacros: Record<string, string>;
  theme?: {
    defaultMode?: 'light' | 'dark';
  };
}

export interface ParityReport {
  // Flat properties for existing unit/E2E test suite compatibility
  totalRoutes: number;
  matchedRoutes: number;
  missingRoutes: string[];
  totalAnchors: number;
  matchedAnchors: number;
  missingAnchors: string[];
  passed: boolean;

  // Structured properties for SCOPE.md & Corpus Gates
  routes: {
    total: number;
    preserved: number;
    missing: string[];
    matched: Record<string, string>;
  };
  anchors: {
    total: number;
    preserved: number;
    missing: string[];
  };
  links: {
    total: number;
    valid: number;
    broken: string[];
  };
  parityScore: number; // 0.0 to 1.0 (1.0 = 100%)
}

export type ParityCheckResult = ParityReport;

export interface MigrationOptions {
  verify?: boolean;
  json?: boolean;
  strict?: boolean;
  reportFormat?: 'json' | 'summary';
  silent?: boolean;
}

export interface MigrationResult {
  config: ConvertedLumenConfig;
  documentsMigrated: number;
  parity?: ParityReport;
}
