import { describe, it, expect, vi, afterAll } from 'vitest';
import { rmSync, existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import {
  convertDocusaurusConfig,
  convertDocusaurusSidebars,
  convertSidebarItem,
  migrateMarkdownToPdx,
  transformCallouts,
  stripThemeImports,
  resolveLinks,
  extractKatexMacrosFromConfig,
  verifyUrlAndAnchorParity,
  compareUrlArrays,
  normalizeUrl,
  normalizeAnchor,
  runLumenMigrateCli,
} from '@omnitron-dev/lumen-migrate';
import { parseDocument, toHtmlSsr } from '@omnitron-dev/lumen-ast';

describe('Challenger M5: Adversarial Stress-Testing of @omnitron-dev/lumen-migrate', () => {
  const tempDirsToClean: string[] = [];

  afterAll(() => {
    for (const dir of tempDirsToClean) {
      if (existsSync(dir)) {
        try {
          rmSync(dir, { recursive: true, force: true });
        } catch {
          // Ignore cleanup errors
        }
      }
    }
  });

  // =========================================================================
  // Domain 1: Docusaurus Config & Sidebar Migration Stress
  // =========================================================================
  describe('Domain 1: Docusaurus Config & Sidebar Migration Stress', () => {
    it('handles deeply recursive sidebar categories exceeding 15 levels without stack overflow', () => {
      const MAX_DEPTH = 16;
      let currentCategory: any = {
        type: 'doc',
        id: 'leaf-document-node',
        label: 'Leaf Document',
      };

      for (let level = MAX_DEPTH; level >= 1; level--) {
        currentCategory = {
          type: 'category',
          label: `Category Level ${level}`,
          collapsed: level % 2 === 0,
          collapsible: true,
          items: [currentCategory],
        };
      }

      const inputSidebars = {
        deepHierarchySidebar: [currentCategory],
      };

      const converted = convertDocusaurusSidebars(inputSidebars);
      expect(converted).toBeDefined();
      expect(converted['deepHierarchySidebar']).toHaveLength(1);

      // Traverse down the converted tree and verify all 16 levels
      let node: any = converted['deepHierarchySidebar'][0];
      for (let level = 1; level <= MAX_DEPTH; level++) {
        expect(node.type).toBe('category');
        expect(node.label).toBe(`Category Level ${level}`);
        expect(node.collapsed).toBe(level % 2 === 0);
        expect(node.items).toHaveLength(1);
        node = node.items[0];
      }

      // Final leaf assertion
      expect(node.type).toBe('doc');
      expect(node.id).toBe('leaf-document-node');
    });

    it('handles mixed shorthand strings, category slugs, and autogenerated items with special characters', () => {
      const rawSidebar = {
        mixedSidebar: [
          'shorthand-root-doc',
          {
            type: 'category',
            label: 'Advanced Guides',
            link: {
              type: 'generated-index',
              title: 'Guides Overview',
              slug: '/guides/index-overview',
            },
            items: [
              'nested-shorthand-item',
              {
                type: 'autogenerated',
                dirName: 'subsystem/@v2.5/custom_chars-#99',
              },
            ],
          },
          {
            type: 'link',
            label: 'External Reference',
            href: 'https://example.com/spec',
          },
          // Cyclical navigation hrefs
          {
            type: 'link',
            label: 'Cycle Forward to B',
            href: '/docs/node-b',
          },
          {
            type: 'link',
            label: 'Cycle Backward to A',
            href: '/docs/node-a',
          },
          // Unrecognized custom plugin item
          {
            type: 'custom-widget',
            widgetName: 'interactive-calc',
          },
        ],
      };

      const converted = convertDocusaurusSidebars(rawSidebar);
      const items = converted['mixedSidebar'];
      expect(items).toHaveLength(6);

      // Shorthand string converted to doc
      expect(items[0]).toEqual({ type: 'doc', id: 'shorthand-root-doc' });

      // Category with link slug
      const category: any = items[1];
      expect(category.type).toBe('category');
      expect(category.label).toBe('Advanced Guides');
      expect(category.href).toBe('/guides/index-overview');
      expect(category.items).toHaveLength(2);
      expect(category.items[0]).toEqual({ type: 'doc', id: 'nested-shorthand-item' });
      expect(category.items[1]).toEqual({
        type: 'autogenerated',
        dirName: 'subsystem/@v2.5/custom_chars-#99',
      });

      // Link items
      expect(items[2]).toEqual({
        type: 'link',
        label: 'External Reference',
        href: 'https://example.com/spec',
      });
      expect(items[3]).toEqual({
        type: 'link',
        label: 'Cycle Forward to B',
        href: '/docs/node-b',
      });
      expect(items[4]).toEqual({
        type: 'link',
        label: 'Cycle Backward to A',
        href: '/docs/node-a',
      });

      // Untyped custom item preserved safely
      expect(items[5]).toEqual({
        type: 'custom-widget',
        widgetName: 'interactive-calc',
      });
    });

    it('robustly transforms malformed, partial, and unexpected docusaurus.config inputs', () => {
      // 1. Completely empty config
      const emptyResult = convertDocusaurusConfig({});
      expect(emptyResult.title).toBe('Migrated Documentation');
      expect(emptyResult.baseUrl).toBe('/');
      expect(emptyResult.locales).toEqual(['en']);
      expect(emptyResult.defaultLocale).toBe('en');
      expect(emptyResult.sidebars).toEqual({});
      expect(emptyResult.katexMacros).toEqual({});

      // 2. Unexpected types and corrupted properties
      const malformedConfig = {
        title: 999999 as any,
        tagline: false as any,
        url: null as any,
        baseUrl: 123 as any,
        trailingSlash: true,
        onBrokenLinks: 'warn',
        i18n: 'corrupted-i18n-string' as any,
        themeConfig: {
          colorMode: { defaultMode: 'light' },
        },
        plugins: [
          null,
          undefined,
          1001,
          '@docusaurus/plugin-content-blog',
          ['@docusaurus/plugin-ideal-image', { size: 400 }],
        ],
      };

      const converted = convertDocusaurusConfig(malformedConfig as any);
      expect(converted.title).toBe('Migrated Documentation'); // Fallback on non-string
      expect(converted.baseUrl).toBe('/'); // Fallback on non-string
      expect(converted.trailingSlash).toBe(true);
      expect(converted.onBrokenLinks).toBe('warn');
      expect(converted.locales).toEqual(['en']); // Safe fallback from string i18n
      expect(converted.defaultLocale).toBe('en');
      expect(converted.theme?.defaultMode).toBe('light');

      // 3. Trailing slash variation: explicitly false
      const falseSlash = convertDocusaurusConfig({ trailingSlash: false });
      expect(falseSlash.trailingSlash).toBe(false);
    });
  });

  // =========================================================================
  // Domain 2: AST & Macro Transformation Stress
  // =========================================================================
  describe('Domain 2: AST & Macro Transformation Stress', () => {
    it('transforms and compiles deeply nested multi-level admonitions (:::note in :::tip in :::danger)', async () => {
      const nestedAdmonitionInput = `
:::::danger Critical Security Advisory
Outer perimeter notice.

::::tip Performance Recommendation
Intermediate cache guideline.

:::note Deep Architectural Detail
Innermost note describing ring buffer semantics.
:::
::::
:::::
`;

      const transformedPdx = migrateMarkdownToPdx(nestedAdmonitionInput);

      // Verify directive attribute transformations
      expect(transformedPdx).toContain(':::::danger{title="Critical Security Advisory"}');
      expect(transformedPdx).toContain('::::tip{title="Performance Recommendation"}');
      expect(transformedPdx).toContain(':::note{title="Deep Architectural Detail"}');

      // Verify AST compilation and HTML SSR compatibility
      const ast = await parseDocument(transformedPdx, 'docs/stress-admonitions.pdx');
      expect(ast).toBeDefined();
      expect(ast.diagnostics).toBeDefined();

      const html = toHtmlSsr(ast);
      expect(html).toContain('Critical Security Advisory');
      expect(html).toContain('Performance Recommendation');
      expect(html).toContain('Deep Architectural Detail');
    });

    it('correctly handles admonitions with inner quotes, markdown syntax in titles, and titles with colons', () => {
      const rawMarkdown = [
        ':::warning "Do Not Bypass: Direct Hardware Memory Access"',
        'Direct access content',
        ':::',
        ':::tip **Pro-Tip**: Use `pnpm --filter` for *isolated* builds',
        'Tip content',
        ':::',
        ':::danger Alert: Memory Allocation Failed: Heap Exhaustion: Error Code 0x88',
        'Danger content',
        ':::',
        ':::info[System Status: 100% Operational]',
        'Info content',
        ':::',
      ].join('\n');

      const transformed = transformCallouts(rawMarkdown);

      // Inner quotes escaped/normalized
      expect(transformed).toContain(':::warning{title="Do Not Bypass: Direct Hardware Memory Access"}');
      // Markdown formatting preserved in title attribute
      expect(transformed).toContain(':::tip{title="**Pro-Tip**: Use `pnpm --filter` for *isolated* builds"}');
      // Titles with multiple colons preserved completely
      expect(transformed).toContain(
        ':::danger{title="Alert: Memory Allocation Failed: Heap Exhaustion: Error Code 0x88"}'
      );
      // Bracketed title syntax normalized to title attribute
      expect(transformed).toContain(':::info{title="System Status: 100% Operational"}');
    });

    it('safely handles raw JSX, unclosed tags, and unescaped curly braces in code blocks vs inline code vs prose', async () => {
      const rawDoc = `---
title: JSX & Braces Stress Test
sidebar_position: "42"
---

import Tabs from '@theme/Tabs';
import TabItem from '@theme/TabItem';

# JSX and Curly Braces Verification

Unclosed void elements: <img src="illustration.png"> and <br>

Prose expressions: User profile {user.firstName} {user.lastName} with id {100 + 23}.
Object mapping in prose: Setting { key: "value", count: 12 }.

Inline code expressions: \`{user.id}\` and \`const obj = { enabled: true };\`.

<Tabs>
  <TabItem value="config">Config Tab</TabItem>
</Tabs>

\`\`\`typescript
export interface Config {
  user: { name: string; age: number };
  template: \`\${string}\`;
}
\`\`\`
`;

      const pdx = migrateMarkdownToPdx(rawDoc);

      // Verify frontmatter normalization (numeric string "42" converted to number 42)
      expect(pdx).toContain('sidebar_position: 42');
      // Verify theme import removal while preserving JSX elements
      expect(pdx).not.toContain('@theme/Tabs');
      expect(pdx).not.toContain('@theme/TabItem');
      expect(pdx).toContain('<Tabs>');
      expect(pdx).toContain('<TabItem value="config">');
      // Verify prose curly braces preserved
      expect(pdx).toContain('{user.firstName}');
      expect(pdx).toContain('{ key: "value", count: 12 }');
      // Verify inline code and block preserved
      expect(pdx).toContain('`{user.id}`');
      expect(pdx).toContain('export interface Config');

      // Verify lumen-ast compilation
      const ast = await parseDocument(pdx, 'docs/jsx-stress.pdx');
      expect(ast).toBeDefined();
      const html = toHtmlSsr(ast);
      expect(html).toContain('lumen-doc');
    });

    it('preserves Cyrillic, emoji, and special characters in heading anchors and cross links', () => {
      const markdown = `
# Multilingual Anchors

[Link to Cyrillic](./theory/foundations.md#квантовые-вычисления)
[Link to Rocket](./performance.md#rocket-boost-🚀)
[Link to API](./api/reference.md#api:v2-methods)
[Link to German](./system.md#überwachung-system)
`;

      const resolved = resolveLinks(markdown);
      expect(resolved).toContain('[Link to Cyrillic](./theory/foundations#квантовые-вычисления)');
      expect(resolved).toContain('[Link to Rocket](./performance#rocket-boost-🚀)');
      expect(resolved).toContain('[Link to API](./api/reference#api:v2-methods)');
      expect(resolved).toContain('[Link to German](./system#überwachung-system)');

      // Verify percent-encoded anchor normalization
      expect(
        normalizeAnchor(
          '#%D0%BA%D0%B2%D0%B0%D0%BD%D1%82%D0%BE%D0%B2%D1%8B%D0%B5-%D0%B2%D1%8B%D1%87%D0%B8%D1%81%D0%BB%D0%B5%D0%BD%D0%B8%D1%8F'
        )
      ).toBe('#квантовые-вычисления');
      expect(normalizeAnchor('#rocket-boost-%F0%9F%9A%80')).toBe('#rocket-boost-🚀');
      expect(normalizeAnchor('#%C3%BCberwachung-system')).toBe('#überwachung-system');
      expect(normalizeAnchor('#api:v2-methods')).toBe('#api:v2-methods');
    });

    it('extracts KaTeX macros across recursive plugins, preset options, LaTeX backslashes, and empty definitions', () => {
      const complexConfig = {
        katexMacros: {
          '\\R': '\\mathbb{R}',
          '\\bm': '\\boldsymbol{#1}',
          '\\empty': '',
        },
        presets: [
          [
            '@docusaurus/preset-classic',
            {
              docs: {
                rehypePlugins: [
                  ['rehype-katex', { macros: { '\\C': '\\mathbb{C}', '\\pd': '\\frac{\\partial}{\\partial #1}' } }],
                  null,
                  undefined,
                  12345,
                ],
              },
            },
          ],
          null,
          undefined,
          'simple-preset-string',
        ],
        plugins: [
          null,
          ['custom-docs', { rehypePlugins: [['rehype-katex', { macros: { '\\E': '\\mathbb{E}' } }]] }],
          ['empty-options', {}],
          ['null-options', null],
        ],
        rehypePlugins: [
          ['rehype-katex', { macros: { '\\N': '\\mathbb{N}', '\\Var': '\\operatorname{Var}_{#1}(#2)' } }],
        ],
      };

      const extracted = extractKatexMacrosFromConfig(complexConfig);

      expect(extracted['\\R']).toBe('\\mathbb{R}');
      expect(extracted['\\bm']).toBe('\\boldsymbol{#1}');
      expect(extracted['\\empty']).toBe('');
      expect(extracted['\\C']).toBe('\\mathbb{C}');
      expect(extracted['\\pd']).toBe('\\frac{\\partial}{\\partial #1}');
      expect(extracted['\\E']).toBe('\\mathbb{E}');
      expect(extracted['\\N']).toBe('\\mathbb{N}');
      expect(extracted['\\Var']).toBe('\\operatorname{Var}_{#1}(#2)');
    });
  });

  // =========================================================================
  // Domain 3: Parity Engine Scale & Adversarial URL Normalization
  // =========================================================================
  describe('Domain 3: Parity Engine Scale & Adversarial URL Normalization', () => {
    it('verifies 20,000 routes and anchors in under 500ms with 100% precision', () => {
      const ROUTE_COUNT = 10_000;
      const ANCHOR_COUNT = 10_000;
      const sourceUrls: string[] = [];
      const targetUrls: string[] = [];

      for (let i = 0; i < ROUTE_COUNT; i++) {
        const route = `/docs/cluster-${i % 250}/service-${i}`;
        sourceUrls.push(route);
        targetUrls.push(route);
      }

      for (let i = 0; i < ANCHOR_COUNT; i++) {
        const anchor = `/docs/cluster-${i % 250}/service-${i}#metric-section-${i % 10}`;
        sourceUrls.push(anchor);
        targetUrls.push(anchor);
      }

      expect(sourceUrls).toHaveLength(20_000);
      expect(targetUrls).toHaveLength(20_000);

      const startTime = performance.now();
      const report = verifyUrlAndAnchorParity(sourceUrls, targetUrls);
      const durationMs = performance.now() - startTime;

      expect(report.passed).toBe(true);
      expect(report.totalRoutes).toBe(ROUTE_COUNT);
      expect(report.matchedRoutes).toBe(ROUTE_COUNT);
      expect(report.totalAnchors).toBe(ANCHOR_COUNT);
      expect(report.matchedAnchors).toBe(ANCHOR_COUNT);
      expect(report.missingRoutes).toEqual([]);
      expect(report.missingAnchors).toEqual([]);
      expect(report.parityScore).toBe(1.0);
      expect(durationMs).toBeLessThan(500);
    });

    it('reconciles adversarial URL pairings: trailing slashes, percent-encoded anchors, and query fragments', () => {
      // 1. Trailing slash reconciliation
      const sourceSlashes = ['/docs/intro/', '/docs/guides/setup/', '/docs/api/v2/'];
      const targetClean = ['/docs/intro', '/docs/guides/setup', '/docs/api/v2'];
      const slashReport = verifyUrlAndAnchorParity(sourceSlashes, targetClean);
      expect(slashReport.passed).toBe(true);
      expect(slashReport.matchedRoutes).toBe(3);

      // 2. URL-encoded vs decoded Unicode Cyrillic and emoji anchors
      const sourceEncoded = [
        '/docs/math#%D1%82%D0%B5%D0%BE%D1%80%D0%B5%D0%BC%D0%B0-%D1%8D%D0%B9%D0%BB%D0%B5%D1%80%D0%B0',
        '/docs/speed#rocket-launch-%F0%9F%9A%80',
      ];
      const targetDecoded = ['/docs/math#теорема-эйлера', '/docs/speed#rocket-launch-🚀'];
      const anchorReport = verifyUrlAndAnchorParity(sourceEncoded, targetDecoded);
      expect(anchorReport.passed).toBe(true);
      expect(anchorReport.totalAnchors).toBe(2);
      expect(anchorReport.matchedAnchors).toBe(2);

      // 3. Hash link fragments with query parameters
      const sourceQueryHash = ['/doc?v=1#anchor', '/doc?v=2#benchmark'];
      const targetQueryHash = ['/doc?v=1#anchor', '/doc?v=2#benchmark'];
      const queryReport = verifyUrlAndAnchorParity(sourceQueryHash, targetQueryHash);
      expect(queryReport.passed).toBe(true);
      expect(queryReport.totalAnchors).toBe(2);
      expect(queryReport.matchedAnchors).toBe(2);

      // 4. Multiple leading slashes isolation
      expect(normalizeUrl('/docs/normal')).toBe('/docs/normal');
      expect(normalizeUrl('/docs/normal/')).toBe('/docs/normal');
    });

    it('precisely separates missing routes from missing anchors with exact diagnostic accuracy', () => {
      const source = [
        '/docs/doc-1',
        '/docs/doc-1#section-1',
        '/docs/doc-1#section-2',
        '/docs/doc-2',
        '/docs/doc-2#section-a',
        '/docs/missing-page-x',
        '/docs/missing-page-y',
        '/docs/doc-2#missing-anchor-b',
        '/docs/doc-2#missing-anchor-c',
      ];

      const target = [
        '/docs/doc-1',
        '/docs/doc-1#section-1',
        '/docs/doc-1#section-2',
        '/docs/doc-2',
        '/docs/doc-2#section-a',
      ];

      const report = verifyUrlAndAnchorParity(source, target);

      expect(report.passed).toBe(false);
      expect(report.totalRoutes).toBe(4);
      expect(report.matchedRoutes).toBe(2);
      expect(report.missingRoutes).toEqual(['/docs/missing-page-x', '/docs/missing-page-y']);

      expect(report.totalAnchors).toBe(5);
      expect(report.matchedAnchors).toBe(3);
      expect(report.missingAnchors).toEqual(['/docs/doc-2#missing-anchor-b', '/docs/doc-2#missing-anchor-c']);

      expect(report.parityScore).toBe(Number((5 / 9).toFixed(4)));
    });
  });

  // =========================================================================
  // Domain 4: CLI Binary Stress
  // =========================================================================
  describe('Domain 4: CLI Binary Stress', () => {
    it('fails closed on docusaurus migration of non-existent directories with --verify and --json', async () => {
      const tempNonExistentSource = join(tmpdir(), `lumen-challenger-nonexistent-src-${Date.now()}`);
      const tempTarget = join(tmpdir(), `lumen-challenger-cli-target-${Date.now()}`);
      tempDirsToClean.push(tempTarget);

      const logSpy = vi.spyOn(console, 'log').mockImplementation(() => {});
      const prevExitCode = process.exitCode;
      try {
        await runLumenMigrateCli(['docusaurus', tempNonExistentSource, tempTarget, '--verify', '--json']);

        expect(logSpy).toHaveBeenCalled();
        const rawOutput = logSpy.mock.calls.map((c) => c[0]).join('\n');
        const parsed = JSON.parse(rawOutput);

        expect(parsed).toBeDefined();
        expect(parsed.config).toBeDefined();
        expect(parsed.config.title).toBe('Migrated Documentation');
        expect(parsed.documentsMigrated).toBe(0);
        expect(parsed.parity).toBeDefined();
        expect(parsed.parity.passed).toBe(false);
        expect(process.exitCode).toBe(1);
      } finally {
        process.exitCode = prevExitCode ?? 0;
        logSpy.mockRestore();
      }
    });

    it('fails closed on verify command against empty/non-existent paths returning structured JSON report', async () => {
      const logSpy = vi.spyOn(console, 'log').mockImplementation(() => {});
      const prevExitCode = process.exitCode;
      try {
        await runLumenMigrateCli([
          'verify',
          join(tmpdir(), 'challenger-nonexistent-a'),
          join(tmpdir(), 'challenger-nonexistent-b'),
          '--json',
        ]);

        expect(logSpy).toHaveBeenCalled();
        const rawOutput = logSpy.mock.calls.map((c) => c[0]).join('\n');
        const parsed = JSON.parse(rawOutput);

        expect(parsed.passed).toBe(false);
        expect(parsed.totalRoutes).toBe(0);
        expect(parsed.totalAnchors).toBe(0);
        expect(parsed.parityScore).toBe(0);
        expect(process.exitCode).toBe(1);
      } finally {
        process.exitCode = prevExitCode ?? 0;
        logSpy.mockRestore();
      }
    });

    it('handles CLI global flags --version and --help without throwing', async () => {
      const logSpy = vi.spyOn(console, 'log').mockImplementation(() => {});

      await runLumenMigrateCli(['--version']);
      expect(logSpy.mock.calls[0]?.[0]).toMatch(/^0\.\d+\.\d+$/);

      logSpy.mockClear();
      await runLumenMigrateCli(['--help']);
      const helpOutput = logSpy.mock.calls.map((c) => c[0]).join('\n');
      expect(helpOutput).toContain('Usage:');
      expect(helpOutput).toContain('lumen-migrate');

      logSpy.mockRestore();
    });
  });
});
