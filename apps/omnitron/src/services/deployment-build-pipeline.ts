import { createHash } from 'node:crypto';
import { isDeepStrictEqual } from 'node:util';
import type { DeploymentPipelineActivity, PipelineDef, PipelineStep } from '../shared/dto/pipelines.js';
import { isReleaseId } from '../release/load.js';
import type { SSHTarget } from '../execution/execution.service.js';
import type { INode } from '../shared/dto/nodes.js';

type Build = Extract<DeploymentPipelineActivity, { kind: 'build' }>;
type Inputs = Pick<Build, 'project' | 'stack' | 'nodeId' | 'projectCommit' | 'omniCommit'>;
const name = /^[a-zA-Z0-9][a-zA-Z0-9._-]{0,127}$/;
const gitOid = /^(?:[a-f0-9]{40}|[a-f0-9]{64})$/;
const sum = (value: unknown): value is string => typeof value === 'string' && /^[a-f0-9]{64}$/.test(value);

export function buildIssuerDigest(node: INode, ssh: SSHTarget): string {
  if (node.isLocal || !node.createdAt || node.host !== ssh.host || node.sshPort !== ssh.port || node.sshUser !== ssh.username ||
      typeof ssh.expectedHostFingerprint !== 'string' || !/^SHA256:[A-Za-z0-9+/]{43}$/.test(ssh.expectedHostFingerprint))
    throw Error('Release builds require the registered issuer and its pinned SSH fingerprint');
  return createHash('sha256').update(JSON.stringify([node.id, node.createdAt, ssh.host, ssh.port, ssh.username, ssh.expectedHostFingerprint])).digest('hex');
}

export function deploymentBuildArgs({ project, stack, nodeId, projectCommit, omniCommit }: Inputs) {
  if (![project, stack, nodeId].every(value => typeof value === 'string' && name.test(value)) || nodeId === 'local' ||
      ![projectCommit, omniCommit].every(value => typeof value === 'string' && gitOid.test(value)))
    throw Error('A registered remote issuer, project, stack and two full Git revisions are required');
  return ['--json', 'release', 'build', project, '--for', stack, '--project-commit', projectCommit, '--omni-commit', omniCommit, '--journal'];
}

export function deploymentBuildDefinition(input: Inputs): PipelineDef {
  const { nodeId } = input;
  const run = ['omnitron', ...deploymentBuildArgs(input)].join(' ');
  return { name: 'release-build-' + createHash('sha256').update(JSON.stringify([nodeId, run])).digest('hex'),
    description: 'Build the pinned project and framework revisions on the registered issuer.', triggers: [{ type: 'manual', config: {} }],
    steps: [{ kind: 'shell', name: 'build-release', nodeId, retries: 0, timeout: 86_400_000, run }] };
}

/** Classify only the command generated by release plan-build. Arbitrary shell output has no release identity. */
export function deploymentBuildInput(step: PipelineStep): Build | undefined {
  if (step.name !== 'build-release' || step.kind !== 'shell' || !step.nodeId) return undefined;
  const match = /^omnitron --json release build ([\w.-]+) --for ([\w.-]+) --project-commit ([a-f0-9]+) --omni-commit ([a-f0-9]+) --journal$/.exec(step.run);
  if (!match) return undefined;
  const input = { project: match[1]!, stack: match[2]!, projectCommit: match[3]!, omniCommit: match[4]!, nodeId: step.nodeId };
  if (![input.project, input.stack, input.nodeId].every(value => name.test(value)) || input.nodeId === 'local' ||
      !gitOid.test(input.projectCommit) || !gitOid.test(input.omniCommit)) return undefined;
  return isDeepStrictEqual(deploymentBuildDefinition(input).steps[0], step) ? { kind: 'build', ...input } : undefined;
}

export function buildJournalReceipt(output: string | undefined, activity: Build) {
  if (!output) return undefined;
  try {
    const result = JSON.parse(output);
    const receipt = result?.data;
    if (result.ok === true && receipt?.protocol === 1 && receipt.project === activity.project && receipt.stack === activity.stack &&
        receipt.projectCommit === activity.projectCommit && receipt.omniCommit === activity.omniCommit &&
        typeof receipt.releaseId === 'string' && isReleaseId(receipt.releaseId) &&
        sum(receipt.manifestSha256))
      return { releaseId: receipt.releaseId as string, manifestSha256: receipt.manifestSha256 as string };
  } catch { /* Missing or incomplete output cannot identify a produced manifest. */ }
  return undefined;
}

/** Project just the contract fields. An unknown or malformed historic observation has no authority. */
export function readActivity(value: unknown, receipt?: unknown): DeploymentPipelineActivity | undefined {
  if (!value || typeof value !== 'object') return undefined;
  const data = value as Record<string, unknown>;
  const { project, stack, nodeId, kind, releaseId, manifestSha256, recoveryReleaseId, recoveryManifestSha256, projectCommit, omniCommit } = data;
  if (typeof project !== 'string' || !name.test(project) || typeof stack !== 'string' || !name.test(stack) ||
      typeof nodeId !== 'string' || !name.test(nodeId)) return undefined;
  if (kind === 'rehearsal' && typeof releaseId === 'string' && isReleaseId(releaseId) && sum(manifestSha256) &&
      typeof recoveryReleaseId === 'string' && isReleaseId(recoveryReleaseId) && sum(recoveryManifestSha256))
    return { kind, project, stack, nodeId, releaseId, manifestSha256, recoveryReleaseId, recoveryManifestSha256 };
  if (kind !== 'build' || typeof projectCommit !== 'string' || !gitOid.test(projectCommit) || typeof omniCommit !== 'string' || !gitOid.test(omniCommit))
    return undefined;
  const bound = receipt && typeof receipt === 'object' ? receipt as Record<string, unknown> : undefined;
  return { kind, project, stack, nodeId, projectCommit, omniCommit,
    ...(bound && typeof bound['releaseId'] === 'string' && isReleaseId(bound['releaseId']) && sum(bound['manifestSha256']) &&
      { releaseId: bound['releaseId'], manifestSha256: bound['manifestSha256'] }) };
}
