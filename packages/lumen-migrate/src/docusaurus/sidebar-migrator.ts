import type { SidebarItem, SidebarDocItem, SidebarCategoryItem } from '../types.js';

export function convertSidebarItem(item: unknown, seen?: Set<unknown>): SidebarItem {
  const visited = seen instanceof Set ? seen : new Set<unknown>();

  if (typeof item === 'string') {
    return {
      type: 'doc',
      id: item,
    } as SidebarDocItem;
  }

  if (!item || typeof item !== 'object') {
    return item as SidebarItem;
  }

  if (visited.has(item)) {
    const raw = item as Record<string, any>;
    return {
      type: 'category',
      label: raw['label'] ?? 'Cyclic Category',
      items: [],
    } as SidebarCategoryItem;
  }
  visited.add(item);

  const raw = item as Record<string, any>;
  const type = raw['type'];

  if (type === 'doc') {
    const docItem: SidebarDocItem = {
      type: 'doc',
      id: raw['id'],
    };
    if (raw['label']) docItem.label = raw['label'];
    return docItem;
  }

  if (type === 'category') {
    const rawItems: unknown[] = Array.isArray(raw['items']) ? raw['items'] : [];
    const convertedItems = rawItems
      .filter((child) => !visited.has(child))
      .map((child) => convertSidebarItem(child, new Set(visited)));

    const categoryItem: SidebarCategoryItem = {
      type: 'category',
      label: raw['label'] ?? 'Category',
      items: convertedItems,
    };

    if (raw['collapsed'] !== undefined) categoryItem.collapsed = Boolean(raw['collapsed']);
    if (raw['collapsible'] !== undefined) categoryItem.collapsible = Boolean(raw['collapsible']);

    if (raw['link'] && typeof raw['link'] === 'object') {
      categoryItem.link = raw['link'];
      if (raw['link']['slug']) {
        categoryItem.href = raw['link']['slug'];
      }
    } else if (raw['href']) {
      categoryItem.href = raw['href'];
    }

    return categoryItem;
  }

  if (type === 'link') {
    return {
      type: 'link',
      label: raw['label'] ?? '',
      href: raw['href'] ?? '',
    };
  }

  if (type === 'autogenerated') {
    return {
      type: 'autogenerated',
      dirName: raw['dirName'] ?? '.',
    };
  }

  // Fallback for custom or untyped items
  return raw as SidebarItem;
}

export function convertDocusaurusSidebars(rawSidebars: Record<string, unknown>): Record<string, unknown[]> {
  const converted: Record<string, unknown[]> = {};

  for (const [key, val] of Object.entries(rawSidebars)) {
    if (Array.isArray(val)) {
      converted[key] = val.map((item) => convertSidebarItem(item));
    } else if (val && typeof val === 'object') {
      converted[key] = [convertSidebarItem(val)];
    }
  }

  return converted;
}
