import { remoteNode } from './host-upgrade.js';

/** Private on-node snapshots survive controller failure; application data is never copied or replaced. */
export function publishNodeConfigCommand(input: {
  directory: string; project: string; body: string; operation: string;
  artifacts: ReadonlyArray<{ app: string; version: string; directory?: string }>;
}): string {
  return remoteNode(`import fs from 'node:fs'; import path from 'node:path'; import {pathToFileURL} from 'node:url'; import {createHash} from 'node:crypto';
    const input=${JSON.stringify(input)};
    const directory=input.directory;
    fs.mkdirSync(directory,{recursive:true,mode:0o700});
    const snapshot=path.join(directory,'.registration-'+input.operation);
    fs.mkdirSync(snapshot,{mode:0o700});
    const files=['omnitron.config.mjs','omnitron.host-upgrade.json','.omnitron-config-sha256'];
    const present=files.filter(name=>fs.existsSync(path.join(directory,name)));
    for(const name of present) fs.copyFileSync(path.join(directory,name),path.join(snapshot,name));
    fs.writeFileSync(path.join(snapshot,'present.json'),JSON.stringify(present),{mode:0o600});
    const write=(file,body)=>{const temporary=file+'.part-'+input.operation; const fd=fs.openSync(temporary,'wx',0o600);
      try{fs.writeFileSync(fd,body);fs.fsyncSync(fd)}finally{fs.closeSync(fd)}fs.renameSync(temporary,file)};
    const staged=path.join(snapshot,'candidate.mjs'); write(staged,input.body);
    const candidate=(await import(pathToFileURL(staged).href)).default;
    const configFile=path.join(directory,files[0]);
    const previous=fs.existsSync(configFile)?(await import(pathToFileURL(configFile).href)).default:null;
    const merged=new Map((previous?.apps??[]).map(app=>[app.name,app]));
    for(const app of candidate.apps) merged.set(app.name,app);
    candidate.apps=[...merged.values()];
    candidate.stacks={...previous?.stacks,...candidate.stacks,deployed:{type:'local',apps:candidate.apps.map(app=>app.name)}};
    const body='// Generated by Omnitron. Contains credentials; keep private.\\nexport default '+JSON.stringify(candidate,null,2)+';\\n';
    const hash=createHash('sha256').update(body).digest('hex');
    const changed=!fs.existsSync(configFile)||fs.readFileSync(configFile,'utf8')!==body;
    const contractFile=path.join(directory,files[1]);
    if(fs.existsSync(contractFile)){
      const contract=JSON.parse(fs.readFileSync(contractFile,'utf8'));
      if(contract.schema!==1||!Array.isArray(contract.apps)) throw Error('Unsupported host upgrade contract; configuration retained');
      for(const artifact of input.artifacts){
        const name=input.project+'/deployed/'+artifact.app;
        const binding=contract.apps.find(app=>app.name===name);
        if(!binding) throw Error('Explicit host upgrade contract required for new app: '+name);
        binding.cwd=candidate.apps.find(app=>app.name===artifact.app).cwd;
        binding.version=artifact.version;
        if(fs.realpathSync(binding.cwd)!==binding.cwd) throw Error('Release directory must be canonical: '+name);
      }
      write(contractFile,JSON.stringify(contract,null,2)+'\\n');
    }
    write(configFile,body); write(path.join(directory,files[2]),hash);
    const fd=fs.openSync(directory,'r');try{fs.fsyncSync(fd)}finally{fs.closeSync(fd)}
    console.log(JSON.stringify({changed}));`);
}

export function restoreNodeConfigCommand(directory: string, operation: string): string {
  return remoteNode(`import fs from 'node:fs';import path from 'node:path';
    const directory=${JSON.stringify(directory)},snapshot=path.join(directory,${JSON.stringify('.registration-' + operation)});
    const present=JSON.parse(fs.readFileSync(path.join(snapshot,'present.json'),'utf8'));
    for(const name of ['omnitron.config.mjs','omnitron.host-upgrade.json','.omnitron-config-sha256']){
      const file=path.join(directory,name);
      if(present.includes(name)){const temporary=file+'.restore';fs.copyFileSync(path.join(snapshot,name),temporary);fs.chmodSync(temporary,0o600);fs.renameSync(temporary,file)}
      else fs.rmSync(file,{force:true});
    }
    const fd=fs.openSync(directory,'r');try{fs.fsyncSync(fd)}finally{fs.closeSync(fd)};`);
}
