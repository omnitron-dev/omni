function createClientIslandsBundle(): string {
  return `// Auto-generated by @omnitron-dev/lumen Selective Portal Island Hydration Runtime
export function setupIslandTrigger(el, trigger, onActivate) {
  let activated = false;
  const fire = () => {
    if (activated) return;
    activated = true;
    onActivate();
  };

  if (trigger === 'load') {
    fire();
    return () => {};
  }

  if (trigger === 'visible' && typeof IntersectionObserver !== 'undefined') {
    const observer = new IntersectionObserver((entries) => {
      if (entries.some((entry) => entry.isIntersecting)) {
        observer.disconnect();
        fire();
      }
    });
    observer.observe(el);
    return () => observer.disconnect();
  }

  if (trigger === 'interaction') {
    const events = ['pointerenter', 'click', 'focusin', 'touchstart'];
    const handler = () => {
      for (const evt of events) el.removeEventListener(evt, handler);
      fire();
    };
    for (const evt of events) el.addEventListener(evt, handler, { passive: true });
    return () => {
      for (const evt of events) el.removeEventListener(evt, handler);
    };
  }

  if (typeof requestIdleCallback === 'function') {
    const id = requestIdleCallback(() => fire(), { timeout: 1500 });
    return () => {
      if (typeof cancelIdleCallback === 'function') cancelIdleCallback(id);
    };
  }

  const timer = setTimeout(fire, 120);
  return () => clearTimeout(timer);
}

export function hydrateLumenIslands(customRegistry) {
  if (typeof document === 'undefined') return [];
  const registry = customRegistry || (typeof window !== 'undefined' && window.__LUMEN_ISLANDS__) || {};
  const hydrated = [];
  const targets = document.querySelectorAll('.lumen-portal-island, [data-lumen-island], .lumen-widget, [data-widget]');

  targets.forEach((el) => {
    if (el.getAttribute('data-lumen-hydrated') === 'true') return;
    const islandId = el.getAttribute('data-lumen-island') || el.getAttribute('data-widget') || '';
    const componentName = el.getAttribute('data-component') || el.getAttribute('data-widget') || islandId;
    const trigger = el.getAttribute('data-hydrate') || 'idle';
    let props = {};
    const rawProps = el.getAttribute('data-props');
    if (rawProps) {
      try {
        props = JSON.parse(rawProps);
      } catch {
        props = {};
      }
    }

    setupIslandTrigger(el, trigger, () => {
      el.setAttribute('data-lumen-hydrated', 'true');
      const mountFn = registry[componentName];
      if (typeof mountFn === 'function') {
        el.replaceChildren();
        mountFn(el, props);
      }
      el.dispatchEvent(
        new CustomEvent('lumen:island-hydrate', {
          bubbles: true,
          detail: { islandId, componentName, props },
        })
      );
    });

    hydrated.push(islandId || componentName);
  });

  return hydrated;
}

if (typeof document !== 'undefined') {
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', () => hydrateLumenIslands(), { once: true });
  } else {
    hydrateLumenIslands();
  }
}
`;
}

function astContainsIslandsOrWidgets(nodes?: LumenNode[]): boolean {
  if (!Array.isArray(nodes)) return false;
  for (const node of nodes) {
    if (node.type === 'jsxWidget' || node.type === 'tabs') {
      return true;
    }
    if (
      node.type === 'rawHtmlPlaceholder' &&
      typeof node.raw === 'string' &&
      (node.raw.includes('data-lumen-island') ||
        node.raw.includes('lumen-portal-island') ||
        node.raw.includes('data-widget'))
    ) {
      return true;
    }
    if (Array.isArray(node.children) && astContainsIslandsOrWidgets(node.children)) {
      return true;
    }
  }
  return false;
}

export async function buildStaticSite(
  corpus: CorpusGraph,
  config: LumenConfig,
  options?: SsgBuildOptions
): Promise<SsgBuildResult> {
  const audienceRoles = options?.roles ?? ['anonymous'];
  const projectedCorpus = projectCorpus(corpus, { roles: audienceRoles });
  const documents = projectedCorpus.getAllDocuments();

  const pages = new Map<string, string>();
  const assets = new Map<string, string>();
  const currentAssets: AssetManifest = {};
  const normalizedBase = normalizeBaseUrl(config.baseUrl);

  // 1. Deterministic client CSS and Portal Island ESM bootstrapper bundles
  const stylesCss = createClientStylesheet();
  const stylesHash = computeContentHash(stylesCss);
  const stylesSri = computeSriHash(stylesCss);
  const stylesRelPath = `assets/lumen-styles.${stylesHash}.css`;

  const islandsJs = createClientIslandsBundle();
  const islandsHash = computeContentHash(islandsJs);
  const islandsSri = computeSriHash(islandsJs);
  const islandsRelPath = `assets/lumen-islands.${islandsHash}.js`;

  assets.set(stylesRelPath, stylesCss);
  assets.set(islandsRelPath, islandsJs);

  currentAssets['lumen-styles.css'] = {
    path: stylesRelPath,
    sri: stylesSri,
    sizeBytes: Buffer.byteLength(stylesCss, 'utf8'),
    hash: stylesHash,
  };

  currentAssets['lumen-islands.js'] = {
    path: islandsRelPath,
    sri: islandsSri,
    sizeBytes: Buffer.byteLength(islandsJs, 'utf8'),
    hash: islandsHash,
  };

  const stylesheetLinkTag = `<link rel="stylesheet" href="${normalizedBase}${stylesRelPath}" />`;
  const islandsScriptTag = `<script type="module" src="${normalizedBase}${islandsRelPath}"></script>`;

  // 2. Concurrently render all projected HTML pages without cross-document state leakage (TC-B20-03)
  const renderPromises = documents.map(async (doc) => {
    const rawRoute = (doc.routePath ?? doc.path.replace(/\\/g, '/')).replace(/\.(pdx|md)$/, '');
    const route = rawRoute.startsWith('/') ? rawRoute : `/${rawRoute}`;
    const hasInteractiveIslands = astContainsIslandsOrWidgets(doc.ast?.children);

    const html = doc.ast
      ? renderDocumentHtml(doc.ast, {
          theme: config.theme?.defaultMode ?? 'dark',
          locale: doc.locale ?? config.defaultLocale,
          baseUrl: config.baseUrl,
          currentPath: route,
          extraHead: [stylesheetLinkTag],
          bodyScripts: hasInteractiveIslands ? [islandsScriptTag] : undefined,
          roles: audienceRoles,
        })
      : `<!DOCTYPE html><html><head>${stylesheetLinkTag}</head><body><h1>${escapeHtml(doc.title || doc.id)}</h1></body></html>`;

    const hash = computeContentHash(html);
    const sri = computeSriHash(html);

    currentAssets[`routes${route}.html`] = {
      path: `routes${route}.${hash}.html`,
      sri,
      sizeBytes: Buffer.byteLength(html, 'utf8'),
      hash,
    };

    return { route, html };
  });

  const rendered = await Promise.all(renderPromises);
  for (const { route, html } of rendered) {
    pages.set(route, html);
  }

  // 3. Generate AI Agent endpoints strictly from projected public corpus
  const llmsTxt = generateLlmsTxt(projectedCorpus, config, { roles: audienceRoles });
  const llmsFullTxt = generateLlmsFullTxt(projectedCorpus, config, { roles: audienceRoles });
  const mirrors = generateRouteMirrors(projectedCorpus, config, { roles: audienceRoles });

  currentAssets['llms.txt'] = `assets/llms.${computeContentHash(llmsTxt)}.txt`;
  currentAssets['llms-full.txt'] = `assets/llms-full.${computeContentHash(llmsFullTxt)}.txt`;

  // 4. Generate Pagefind search index shards + portable ESM runtime strictly from projected public corpus
  const searchResult = await buildSearchIndex(projectedCorpus, config, { roles: audienceRoles });
  Object.assign(currentAssets, searchResult.manifestEntries);
  for (const [relPath, fileContent] of Object.entries(searchResult.files)) {
    assets.set(relPath, fileContent);
  }

  // 5. Generate or carry forward asset manifest
  const manifest = options?.carryPreviousBuildForward
    ? carryPreviousBuildForward(options.previousManifest, currentAssets)
    : generateAssetManifest(currentAssets, {
        carryPreviousBuildForward: false,
      });
  assets.set('asset-manifest.json', JSON.stringify(manifest, null, 2));

  // 6. Optional disk materialization
  let resolvedOutDir: string | undefined;
  let writtenFiles: string[] | undefined;

  if (options?.writeToDisk) {
    resolvedOutDir = resolve(options.outDir ?? config.outDir ?? 'dist');
    writtenFiles = [];

    const writeSafeDiskFile = (relPath: string, content: string) => {
      const normalizedRel = relPath.replace(/\\/g, '/').replace(/^\/+/, '');
      if (!normalizedRel || normalizedRel.split('/').includes('..')) {
        return;
      }
      const absTarget = resolve(resolvedOutDir!, normalizedRel);
      if (absTarget !== resolvedOutDir && !absTarget.startsWith(resolvedOutDir! + sep)) {
        return;
      }
      mkdirSync(dirname(absTarget), { recursive: true });
      writeFileSync(absTarget, content, 'utf8');
      writtenFiles!.push(normalizedRel);
    };

    for (const [route, html] of pages.entries()) {
      const cleanRoute = route === '/' ? 'index' : route.replace(/^\/+/, '');
      const htmlRelPath = cleanRoute.endsWith('.html') ? cleanRoute : `${cleanRoute}.html`;
      writeSafeDiskFile(htmlRelPath, html);
    }

    writeSafeDiskFile('llms.txt', llmsTxt);
    writeSafeDiskFile('llms-full.txt', llmsFullTxt);

    for (const [mirrorKey, mdContent] of mirrors.entries()) {
      if (mirrorKey.endsWith('.md')) {
        writeSafeDiskFile(mirrorKey, mdContent);
      }
    }

    for (const [assetPath, assetContent] of assets.entries()) {
      writeSafeDiskFile(assetPath, assetContent);
    }

    writeSafeDiskFile('asset-manifest.json', JSON.stringify(manifest, null, 2));
  }

  return {
    pagesCount: pages.size,
    pages,
    mirrors,
    llmsTxt,
    llmsFullTxt,
    manifest,
    assets,
    ...(resolvedOutDir ? { outDir: resolvedOutDir } : {}),
    ...(writtenFiles ? { writtenFiles } : {}),
  };
}
